function boostUpgrades(): UpgradeDef[] {
  const out: UpgradeDef[] = [];
  for (const g of generators) {
    const names = boostNames[g.id];
    const [costRes, base] = Object.entries(g.baseCost)[0];
    out.push({
      id: `${g.id}_b1`,
      name: names[0],
      icon: g.icon,
      description: `${g.name} ×2.`,
      flavor: names[1],
      cost: { [costRes]: Math.round(base * GROWTH ** 10 * 5) },
      effects: [{ type: 'genMult', gen: g.id, mult: 2 }],
      unlock: { gen: { id: g.id, count: 10 } },
    });
    out.push({
      id: `${g.id}_b2`,
      name: names[2],
      icon: g.icon,
      description: `${g.name} ×3.`,
      flavor: names[3],
      cost: { [costRes]: Math.round(base * GROWTH ** 25 * 5) },
      effects: [{ type: 'genMult', gen: g.id, mult: 3 }],
      unlock: { gen: { id: g.id, count: 25 } },
    });
  }
  return out;
}

